#!/usr/bin/env node
/**
 * Builds src/lib/geo/regionPolygons.ts: coarse land outlines of Denmark, Norway
 * and Sweden, used to pick the map source for a view and the credits of a print.
 *
 * Input: Natural Earth 1:50m admin-0 countries (public domain), e.g.
 *   curl -L -o /tmp/ne/ne50.geojson \
 *     https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_50m_admin_0_countries.geojson
 *   node scripts/build-region-polygons.mjs /tmp/ne/ne50.geojson
 *
 * Rings are simplified (Douglas-Peucker, about 2 km) and tiny islands dropped;
 * Svalbard and Jan Mayen are left out (no Kartverket topo coverage needed there).
 */
import { readFileSync, writeFileSync } from "node:fs";

const [input] = process.argv.slice(2);
if (!input) {
  console.error("Usage: node scripts/build-region-polygons.mjs <ne_50m_admin_0_countries.geojson>");
  process.exit(1);
}

const TOLERANCE_DEG = 0.02;
const MIN_AREA_DEG2 = 0.004;
const COUNTRIES = { dk: "DNK", no: "NOR", se: "SWE" };

const geo = JSON.parse(readFileSync(input, "utf8"));

function perpDist([x, y], [x1, y1], [x2, y2]) {
  const dx = x2 - x1;
  const dy = y2 - y1;
  const len2 = dx * dx + dy * dy;
  if (len2 === 0) return Math.hypot(x - x1, y - y1);
  const t = Math.max(0, Math.min(1, ((x - x1) * dx + (y - y1) * dy) / len2));
  return Math.hypot(x - (x1 + t * dx), y - (y1 + t * dy));
}

function simplify(points, tol) {
  if (points.length < 3) return points;
  const keep = new Uint8Array(points.length);
  keep[0] = keep[points.length - 1] = 1;
  const stack = [[0, points.length - 1]];
  while (stack.length) {
    const [a, b] = stack.pop();
    let max = 0;
    let idx = -1;
    for (let i = a + 1; i < b; i++) {
      const d = perpDist(points[i], points[a], points[b]);
      if (d > max) {
        max = d;
        idx = i;
      }
    }
    if (max > tol && idx > 0) {
      keep[idx] = 1;
      stack.push([a, idx], [idx, b]);
    }
  }
  return points.filter((_, i) => keep[i]);
}

function area(ring) {
  let s = 0;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    s += (ring[j][0] + ring[i][0]) * (ring[j][1] - ring[i][1]);
  }
  return Math.abs(s / 2);
}

const round = (n) => Math.round(n * 1000) / 1000;
const out = {};
for (const [key, iso] of Object.entries(COUNTRIES)) {
  const feature = geo.features.find((f) => f.properties.ADM0_A3 === iso || f.properties.ISO_A3 === iso);
  if (!feature) throw new Error(`No feature for ${iso}`);
  const polys = feature.geometry.type === "Polygon" ? [feature.geometry.coordinates] : feature.geometry.coordinates;
  const rings = [];
  for (const poly of polys) {
    const outer = poly[0]; // holes (lakes) do not matter for picking a source
    if (outer.some(([, lat]) => lat > 72)) continue; // Svalbard, Jan Mayen
    if (area(outer) < MIN_AREA_DEG2) continue;
    const ring = simplify(outer, TOLERANCE_DEG).map(([x, y]) => [round(x), round(y)]);
    if (ring.length >= 4) rings.push(ring);
  }
  out[key] = rings;
  console.error(`${key}: ${rings.length} rings, ${rings.reduce((n, r) => n + r.length, 0)} points`);
}

const body = Object.entries(out)
  .map(([k, rings]) => `  ${k}: [\n${rings.map((r) => `    ${JSON.stringify(r)},`).join("\n")}\n  ],`)
  .join("\n");

writeFileSync(
  new URL("../src/lib/geo/regionPolygons.ts", import.meta.url),
  `// Generated by scripts/build-region-polygons.mjs from Natural Earth 1:50m
// admin-0 countries (public domain). Do not edit by hand.
// Coarse outlines (about 2 km), outer rings only: [lng, lat] pairs.

export type CountryCode = "dk" | "no" | "se";

export const COUNTRY_RINGS: Record<CountryCode, [number, number][][]> = {
${body}
};
`
);
